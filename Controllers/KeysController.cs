using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using KeyRoomSystem.Data;
using KeyRoomSystem.Models;

namespace KeyRoomSystem.Controllers
{
    public class KeysController : Controller
    {
        private readonly ApplicationDbContext _context;

        public KeysController(ApplicationDbContext context)
        {
            _context = context;
        }

        // =========================================================
        // GET: /Keys
        // Display all registered keys
        // =========================================================
        public IActionResult Index()
        {
            if (string.IsNullOrEmpty(
                HttpContext.Session.GetString("UserSession")))
            {
                return RedirectToAction("Login", "Account");
            }

            var keys = _context.KeyItems
                .OrderBy(k => k.Id)
                .ToList();

            return View(keys);
        }


        // =========================================================
        // GET: /Keys/Create
        // Display registration form
        // =========================================================
        [HttpGet]
        public IActionResult Create()
        {
            if (string.IsNullOrEmpty(
                HttpContext.Session.GetString("UserSession")))
            {
                return RedirectToAction("Login", "Account");
            }

            // Show the next expected Key Number on the form.
            // This is only a display value.
            // The actual Key Number is generated from the database Id
            // after the record is saved.
            int nextKeyNumber = 1;

            if (_context.KeyItems.Any())
            {
                nextKeyNumber = _context.KeyItems
                    .Max(k => k.Id) + 1;
            }

            var key = new KeyItem
            {
                KeyNumber = nextKeyNumber.ToString(),
                IsAvailable = true
            };

            return View(key);
        }


        // =========================================================
        // POST: /Keys/Create
        // Register new key
        // =========================================================
        [HttpPost]
        [ValidateAntiForgeryToken]
        public IActionResult Create(KeyItem key)
        {
            if (string.IsNullOrEmpty(
                HttpContext.Session.GetString("UserSession")))
            {
                return RedirectToAction("Login", "Account");
            }

            // KeyNumber is generated by the system.
            // Remove it from ModelState because the user does not
            // supply it.
            ModelState.Remove(nameof(KeyItem.KeyNumber));

            if (!ModelState.IsValid)
            {
                return View(key);
            }

            // Ensure every newly registered key starts as Available.
            key.IsAvailable = true;

            // Do not trust the KeyNumber coming from the browser.
            key.KeyNumber = string.Empty;

            // -----------------------------------------------------
            // STEP 1:
            // Save the record so SQL Server generates the Id.
            // -----------------------------------------------------
            _context.KeyItems.Add(key);
            _context.SaveChanges();

            // -----------------------------------------------------
            // STEP 2:
            // SQL Server has now generated the Id.
            // Use that Id as the Key Number.
            // -----------------------------------------------------
            key.KeyNumber = key.Id.ToString();

            // -----------------------------------------------------
            // STEP 3:
            // Save the generated KeyNumber.
            // -----------------------------------------------------
            _context.SaveChanges();

            TempData["SuccessMessage"] =
                $"Key Number {key.KeyNumber} has been successfully registered.";

            return RedirectToAction(nameof(Index));
        }
    }
}